-- Run this in Supabase SQL Editor after creating the public bucket named product-images.
-- This allows only users registered in public.admin_users to upload, update, or delete images.

create policy "Admins can upload product images"
on storage.objects
for insert
 to authenticated
with check (
  bucket_id = 'product-images'
  and exists (select 1 from public.admin_users where user_id = auth.uid())
);

create policy "Admins can update product images"
on storage.objects
for update
 to authenticated
using (
  bucket_id = 'product-images'
  and exists (select 1 from public.admin_users where user_id = auth.uid())
)
with check (
  bucket_id = 'product-images'
  and exists (select 1 from public.admin_users where user_id = auth.uid())
);

create policy "Admins can delete product images"
on storage.objects
for delete
 to authenticated
using (
  bucket_id = 'product-images'
  and exists (select 1 from public.admin_users where user_id = auth.uid())
);


create table if not exists public.feedback (
  id bigint generated by default as identity primary key,
  name text not null default 'Customer' check (char_length(name) <= 60),
  rating integer not null check (rating between 1 and 5),
  message text not null check (char_length(message) between 1 and 1000),
  created_at timestamptz not null default now()
);

alter table public.feedback enable row level security;

drop policy if exists "Anyone can view feedback" on public.feedback;
create policy "Anyone can view feedback"
  on public.feedback for select
  to anon, authenticated
  using (true);

drop policy if exists "Anyone can submit feedback" on public.feedback;
create policy "Anyone can submit feedback"
  on public.feedback for insert
  to anon, authenticated
  with check (
    rating between 1 and 5
    and char_length(coalesce(name, 'Customer')) <= 60
    and char_length(message) between 1 and 1000
  );